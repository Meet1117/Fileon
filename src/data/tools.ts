export const categories = [
  { id: "all", name: "All Tools", icon: Layers },
  { id: "pdf", name: "PDF Tools", icon: FileText },
  { id: "image", name: "Image Tools", icon: Image },
  { id: "document", name: "Document", icon: FileType2 },
  { id: "utility", name: "Utilities", icon: Download },
] as const;

export type CategoryId = (typeof categories)[number]["id"];

export const getToolsByCategory = (category: CategoryId): Tool[] => {
  if (category === "all") return tools;
  return tools.filter((tool) => tool.category === category);
};

export const getToolById = (id: string): Tool | undefined => {
  return tools.find((tool) => tool.id === id);
};
